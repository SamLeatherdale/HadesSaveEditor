CATALOGS = {"en": EN, "es": ES}
_language = "en"


def get_language() -> str:
    return _language


def set_language(lang: str) -> None:
    global _language
    _language = lang if lang in CATALOGS else "en"


def load_language() -> str:
    env = os.environ.get("HSE_LANG", "").strip().lower()
    if env in CATALOGS:
        set_language(env)
        return _language
    saved = QSettings(_ORGANIZATION, _APPLICATION).value("language", "en")
    set_language(str(saved) if saved else "en")
    return _language


def save_language(lang: str) -> None:
    set_language(lang)
    QSettings(_ORGANIZATION, _APPLICATION).setValue("language", _language)


def t(key: str, **kwargs) -> str:
    text = CATALOGS[_language].get(key)
    if text is None:
        text = CATALOGS["en"].get(key, key)
    if kwargs:
        return text.format(**kwargs)
    return text
